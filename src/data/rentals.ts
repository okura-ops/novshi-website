export interface RentalPhoto {
  /** /images/rent/{slug}/ 配下のファイル名（拡張子なし） */
  file: string;
  alt: string;
}

export interface Rental {
  slug: string;
  /** 物件連番（社内キー） */
  code: string;
  /** 表示名（市町名＋大字。ジモティー掲載と同じ公開粒度） */
  name: string;
  /** 一覧カード用の一行スペック */
  spec: string;
  /** 家賃（円/月） */
  rent: number;
  /** 家賃の補足（選択制賃料など） */
  rentNote?: string;
  /** フリーレント等の主要特典（表示順） */
  perks: string[];
  /** ペット条件 */
  pets: string;
  /** 短期解約違約金（2段階） */
  penalty: string[];
  /** 月額でかかるその他費用 */
  otherFee?: string;
  parking: string;
  layout: string;
  structure: string;
  bldgArea: string;
  landArea?: string;
  built: string;
  access?: string;
  /** インフラ・設備の要点 */
  infra: string[];
  /** 紹介文（ジモティー掲載の承認済み文言をもとにした2〜3文） */
  lead: string;
  /** 向いている使い方・入居者像 */
  highlights: string[];
  /** 先にお伝えしておくこと（ジモティー掲載の開示事項。落とさない） */
  disclosures: string[];
  /**
   * 成約済み（入居が決まった物件）。設定するとページと写真は残したまま、
   * 写真に成約スタンプを重ね、申込導線を止める。一覧では末尾に回る。
   * 募集を再開するときはこのフィールドを消す。
   */
  closed?: {
    /** 状態ラベル（一覧カード・詳細の見出しに出す） */
    label: string;
    /** 入居時期（詳細ページの注記に出す） */
    since: string;
  };
  /** 内覧方式 */
  viewing: 'selfbox' | 'remote';
  address: string;
  /** Notion取得物件管理DBの緯度・経度（地図リンクは住所文字列でなく座標で張る。枝番を地図が解決できない物件があるため） */
  lat: number;
  lng: number;
  jimotyUrl: string;
  albumUrl: string;
  /** 申込フォームのプレフィル値（物件名） */
  formEntry: string;
  photos: RentalPhoto[];
}

export function applyUrl(r: Rental): string {
  return `${APPLY_FORM_BASE}?usp=pp_url&entry.628752138=${encodeURIComponent(r.formEntry)}`;
}

export function mapUrl(r: Rental): string {
  return `https://www.google.com/maps/search/?api=1&query=${r.lat},${r.lng}`;
}

